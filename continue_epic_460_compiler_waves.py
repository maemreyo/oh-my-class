def gh_has_marker(repo, issue, marker):
    raw = run([
        'gh', 'issue', 'view', str(issue), '--repo', REPOSITORY, '--json', 'comments',
    ], repo, capture=True).stdout
    try:
        comments = json.loads(raw).get('comments', [])
    except (ValueError, TypeError):
        return False
    return any(marker in str(comment.get('body', '')) for comment in comments if isinstance(comment, dict))


