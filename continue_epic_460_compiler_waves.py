def run(cmd, cwd, check=True, capture=False):
    print('+', ' '.join(cmd))
    kwargs = {'cwd': str(cwd), 'text': True, 'check': check}
    if capture:
        kwargs['stdout'] = subprocess.PIPE
        kwargs['stderr'] = subprocess.PIPE
    return subprocess.run(cmd, **kwargs)


def git_output(repo, *args):
    return run(['git'] + list(args), repo, capture=True).stdout.strip()


def normalize_remote(remote):
    value = remote.rstrip('/')
    if value.endswith('.git'):
        value = value[:-4]
    return value


def ensure_repo(repo):
    if not (repo / '.git').exists():
        raise RuntimeError('run this script from the oh-my-class repository root')
    remote = git_output(repo, 'remote', 'get-url', 'origin')
    if REPOSITORY not in normalize_remote(remote):
        raise RuntimeError('origin is %r, expected %s' % (remote, REPOSITORY))
    tracked = git_output(repo, 'status', '--porcelain', '--untracked-files=no')
    if tracked:
        raise RuntimeError('tracked worktree is not clean; commit/stash first:\n%s' % tracked)
    ancestry = subprocess.run(
        ['git', 'merge-base', '--is-ancestor', EXPECTED_ANCESTOR, 'HEAD'], cwd=str(repo),
    )
    if ancestry.returncode != 0:
        raise RuntimeError('HEAD does not contain expected committed baseline %s' % EXPECTED_ANCESTOR)


def hash_object(repo, path):
    return git_output(repo, 'hash-object', path)


def changed_paths():
    return sorted(set(NEW_FILES) | set(TRANSFORMS))


def preflight(repo):
    ensure_repo(repo)
    print('HEAD:', git_output(repo, 'rev-parse', 'HEAD'))
    for path, expected in sorted(EXPECTED_BLOBS.items()):
        target = repo / path
        if not target.is_file():
            raise RuntimeError('required base file missing: %s' % path)
        actual = hash_object(repo, path)
        if actual != expected:
            raise RuntimeError('%s blob drift: expected %s, got %s' % (path, expected, actual))
    for path in sorted(NEW_FILES):
        if (repo / path).exists():
            raise RuntimeError('new path already exists; refusing overwrite: %s' % path)
    for path, replacements in sorted(TRANSFORMS.items()):
        text = (repo / path).read_text(encoding='utf-8')
        for old, _new in replacements:
            count = text.count(old)
            if count != 1:
                raise RuntimeError('%s transform anchor count=%d, expected exactly 1' % (path, count))
    print('Preflight passed for %d guarded files and %d new files.' % (len(EXPECTED_BLOBS), len(NEW_FILES)))


def backup_paths(repo, paths, backup_root):
    manifest = {}
    for path in paths:
        target = repo / path
        existed = target.exists()
        manifest[path] = existed
        if existed:
            destination = backup_root / path
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(str(target), str(destination))
    return manifest


def restore_paths(repo, backup_root, manifest):
    for path, existed in manifest.items():
        target = repo / path
        if existed:
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(str(backup_root / path), str(target))
        elif target.exists():
            target.unlink()
    print('Restored every touched path from backup.')


def apply_bundle(repo):
    for path, content in sorted(NEW_FILES.items()):
        target = repo / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding='utf-8')
    for path, replacements in sorted(TRANSFORMS.items()):
        target = repo / path
        text = target.read_text(encoding='utf-8')
        for old, new in replacements:
            if text.count(old) != 1:
                raise RuntimeError('%s changed during apply; refusing ambiguous replacement' % path)
            text = text.replace(old, new)
        target.write_text(text, encoding='utf-8')
    for path in EXECUTABLE_PATHS:
        (repo / path).chmod(0o755)


def verify(repo):
    records = []
    for cmd in VERIFY_COMMANDS:
        started = datetime.now(timezone.utc)
        completed = run(cmd, repo)
        records.append({
            'command': cmd,
            'returncode': completed.returncode,
            'started_at': started.isoformat(),
            'finished_at': datetime.now(timezone.utc).isoformat(),
        })
    return records


def write_patch(repo, patch_out):
    cmd = ['git', 'diff', '--binary', '--'] + changed_paths()
    print('+', ' '.join(cmd), '>', patch_out)
    result = subprocess.run(cmd, cwd=str(repo), stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True)
    if not result.stdout:
        raise RuntimeError('generated patch is empty')
    patch_out.parent.mkdir(parents=True, exist_ok=True)
    patch_out.write_bytes(result.stdout)
    digest = hashlib.sha256(result.stdout).hexdigest()
    print('Patch:', patch_out)
    print('Patch SHA-256:', digest)
    return digest


